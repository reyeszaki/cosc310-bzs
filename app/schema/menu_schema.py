from decimal import Decimal
from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, field_serializer, model_validator

# Strip surrounding whitespace so names and categories cannot be blank.
Text = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1)]
# Decimal validates money without binary-float rounding; accept at most two decimal places.
Price = Annotated[Decimal, Field(gt=0, max_digits=10, decimal_places=2, allow_inf_nan=False)]


class MenuItemCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: Text = Field(description="Menu item name; cannot be blank")
    description: Text = Field(description="Description shown to customers; cannot be blank")
    price: Price = Field(description="Positive price, at most two decimal places and ten total digits")
    category: Text = Field(description="One category per item, for example mains, drinks, or desserts")
    is_available: bool = Field(default=True, description="False means out of stock; item remains visible")

    @field_serializer("price", when_used="json")
    def serialize_price(self, value: Decimal) -> float:
        # Send a JSON number so the frontend can format the price consistently.
        return float(value)


class MenuItem(MenuItemCreate):
    id: int = Field(gt=0, description="Item ID generated by the repository")
    restaurant_id: int = Field(gt=0, description="Restaurant that owns this item")


class MenuItemUpdate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: Text | None = Field(default=None, description="Replacement name; omit to keep current value")
    description: Text | None = Field(default=None, description="Replacement description")
    price: Price | None = Field(default=None, description="Replacement positive price, at most two decimal places")
    category: Text | None = Field(default=None, description="Move the item to this category")
    is_available: bool | None = Field(default=None, description="Set availability to true or false")

    @model_validator(mode="after")
    def require_changes(self) -> "MenuItemUpdate":
        # PATCH permits omitted fields, but explicit null must not erase required data.
        if not self.model_fields_set:
            raise ValueError("Provide at least one field to update")
        if any(getattr(self, field) is None for field in self.model_fields_set):
            raise ValueError("Menu item fields cannot be null")
        return self


class Menu(BaseModel):
    restaurant_id: int = Field(gt=0, description="Restaurant whose menu was requested")
    items: list[MenuItem] = Field(description="Matching items, including unavailable items; may be empty")


class MenuError(BaseModel):
    detail: str = Field(description="Explanation of the missing restaurant or item")
